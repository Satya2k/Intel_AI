/**
 * Northstar Technologies Branded HTML Email Templates
 * Responsive, dark-navy enterprise styling with clean tables, badges, and action buttons.
 */

export interface EmailTemplateRenderResult {
  subject: string;
  html: string;
  text: string;
}

const BRAND_HEADER = `
  <div style="background-color: #0f172a; padding: 24px 32px; border-bottom: 2px solid #3b82f6; text-align: left;">
    <div style="display: flex; align-items: center;">
      <h1 style="color: #ffffff; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; font-size: 20px; font-weight: 700; margin: 0; letter-spacing: -0.5px;">
        NORTHSTAR <span style="color: #60a5fa; font-weight: 400;">TECHNOLOGIES</span>
      </h1>
      <span style="display: inline-block; background-color: #1e293b; color: #94a3b8; font-size: 11px; font-weight: 600; padding: 3px 8px; border-radius: 4px; margin-left: 12px; border: 1px solid #334155;">
        INTELLIDESK 2.0
      </span>
    </div>
  </div>
`;

const BRAND_FOOTER = `
  <div style="background-color: #f8fafc; padding: 20px 32px; border-top: 1px solid #e2e8f0; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; font-size: 12px; color: #64748b; line-height: 1.5;">
    <p style="margin: 0 0 8px 0;">This is an automated communication generated by Northstar Technologies IntelliDesk Service Operations & Governance Engine.</p>
    <p style="margin: 0;">Academic Demonstration Environment • Synthetic Organization Data • ISO 27001 / SOC 2 Type II Simulated Controls</p>
  </div>
`;

export function renderEmailTemplate(templateId: string, variables: Record<string, unknown>): EmailTemplateRenderResult {
  switch (templateId) {
    case 'ticket_confirmation': {
      const ticketId = String(variables.ticketId || 'TCK-2026-XXX');
      const title = String(variables.title || 'IT Service Incident');
      const priority = String(variables.priority || 'P3');
      const assignedTeam = String(variables.assignedTeam || 'End User Computing');
      const slaDueAt = variables.slaDueAt ? new Date(String(variables.slaDueAt)).toLocaleString() : 'Within SLA Target';

      const subject = `[Ticket Confirmed] ${ticketId}: ${title}`;
      const html = `
        <div style="max-width: 600px; margin: 0 auto; background-color: #ffffff; border: 1px solid #e2e8f0; border-radius: 8px; overflow: hidden; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;">
          ${BRAND_HEADER}
          <div style="padding: 32px; color: #1e293b;">
            <div style="margin-bottom: 20px;">
              <span style="background-color: ${priority === 'P1' ? '#fee2e2' : priority === 'P2' ? '#ffedd5' : '#e0f2fe'}; color: ${priority === 'P1' ? '#991b1b' : priority === 'P2' ? '#9a3412' : '#0369a1'}; font-size: 12px; font-weight: 700; padding: 4px 10px; border-radius: 12px;">
                ${priority} INCIDENT
              </span>
              <span style="color: #64748b; font-size: 13px; margin-left: 10px;">ID: <strong>${ticketId}</strong></span>
            </div>
            <h2 style="font-size: 18px; font-weight: 600; margin: 0 0 16px 0; color: #0f172a;">Your Service Desk Ticket Has Been Received</h2>
            <p style="font-size: 14px; line-height: 1.6; color: #334155; margin-bottom: 24px;">
              Your IT support request has been cataloged in the service desk and automatically routed by our AI triage agent.
            </p>
            <table style="width: 100%; border-collapse: collapse; margin-bottom: 24px; font-size: 13px;">
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b; width: 35%;">Summary</td>
                <td style="padding: 10px 0; color: #0f172a; font-weight: 600;">${title}</td>
              </tr>
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b;">Assigned Team</td>
                <td style="padding: 10px 0; color: #0f172a; font-weight: 600;">${assignedTeam}</td>
              </tr>
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b;">SLA Target Due</td>
                <td style="padding: 10px 0; color: #0f172a; font-weight: 600;">${slaDueAt}</td>
              </tr>
            </table>
            <div style="text-align: center; margin-top: 28px;">
              <a href="https://intellidesk-ai-blj5.vercel.app/employee" style="background-color: #2563eb; color: #ffffff; text-decoration: none; padding: 12px 24px; border-radius: 6px; font-weight: 600; font-size: 14px; display: inline-block;">
                Track Ticket Status in Employee Portal
              </a>
            </div>
          </div>
          ${BRAND_FOOTER}
        </div>
      `;
      const text = `Northstar Technologies IntelliDesk\nTicket Confirmed: ${ticketId}\nTitle: ${title}\nPriority: ${priority}\nAssigned Team: ${assignedTeam}\nSLA Due: ${slaDueAt}`;
      return { subject, html, text };
    }

    case 'approval_request': {
      const requestId = String(variables.requestId || 'REQ-2026-XXX');
      const requesterName = String(variables.requesterName || 'Employee');
      const appName = String(variables.appName || 'Enterprise Application');
      const permission = String(variables.permission || 'Access Permission');
      const justification = String(variables.justification || 'Standard business requirement');

      const subject = `[Action Required] Access Approval: ${requesterName} - ${appName}`;
      const html = `
        <div style="max-width: 600px; margin: 0 auto; background-color: #ffffff; border: 1px solid #e2e8f0; border-radius: 8px; overflow: hidden; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;">
          ${BRAND_HEADER}
          <div style="padding: 32px; color: #1e293b;">
            <div style="margin-bottom: 16px;">
              <span style="background-color: #fef3c7; color: #92400e; font-size: 12px; font-weight: 700; padding: 4px 10px; border-radius: 12px;">
                ACTION REQUIRED
              </span>
              <span style="color: #64748b; font-size: 13px; margin-left: 10px;">ID: <strong>${requestId}</strong></span>
            </div>
            <h2 style="font-size: 18px; font-weight: 600; margin: 0 0 16px 0; color: #0f172a;">Identity Governance Approval Required</h2>
            <p style="font-size: 14px; line-height: 1.6; color: #334155; margin-bottom: 24px;">
              An entitlement request submitted by <strong>${requesterName}</strong> requires your managerial authorization.
            </p>
            <table style="width: 100%; border-collapse: collapse; margin-bottom: 24px; font-size: 13px;">
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b; width: 35%;">Requester</td>
                <td style="padding: 10px 0; color: #0f172a; font-weight: 600;">${requesterName}</td>
              </tr>
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b;">Target Application</td>
                <td style="padding: 10px 0; color: #0f172a; font-weight: 600;">${appName}</td>
              </tr>
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b;">Requested Entitlement</td>
                <td style="padding: 10px 0; color: #2563eb; font-weight: 600;">${permission}</td>
              </tr>
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b;">Business Justification</td>
                <td style="padding: 10px 0; color: #0f172a; font-style: italic;">"${justification}"</td>
              </tr>
            </table>
            <div style="text-align: center; margin-top: 28px;">
              <a href="https://intellidesk-ai-blj5.vercel.app/approvals" style="background-color: #059669; color: #ffffff; text-decoration: none; padding: 12px 24px; border-radius: 6px; font-weight: 600; font-size: 14px; display: inline-block;">
                Review and Decide in Approvals Portal
              </a>
            </div>
          </div>
          ${BRAND_FOOTER}
        </div>
      `;
      const text = `Northstar Technologies Governance\nAction Required: Access Approval ${requestId}\nRequester: ${requesterName}\nApp: ${appName}\nPermission: ${permission}\nJustification: ${justification}`;
      return { subject, html, text };
    }

    case 'major_incident_alert': {
      const incidentId = String(variables.incidentId || 'INC-MAJ-2026-001');
      const severity = String(variables.severity || 'SEV-1');
      const title = String(variables.title || 'Production Service Degradation');
      const impact = String(variables.impact || 'Enterprise service disrupted');

      const subject = `[${severity} ALERT] ${title}`;
      const html = `
        <div style="max-width: 600px; margin: 0 auto; background-color: #ffffff; border: 1px solid #e2e8f0; border-radius: 8px; overflow: hidden; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;">
          <div style="background-color: #991b1b; padding: 24px 32px; text-align: left;">
            <h1 style="color: #ffffff; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; font-size: 20px; font-weight: 700; margin: 0;">
              CRITICAL INCIDENT ALERT: ${severity}
            </h1>
          </div>
          <div style="padding: 32px; color: #1e293b;">
            <h2 style="font-size: 18px; font-weight: 600; margin: 0 0 16px 0; color: #0f172a;">${title}</h2>
            <p style="font-size: 14px; line-height: 1.6; color: #334155; margin-bottom: 24px;">
              A high-severity IT operational incident has been declared. Incident commanders and response teams have convened in the war room.
            </p>
            <table style="width: 100%; border-collapse: collapse; margin-bottom: 24px; font-size: 13px;">
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b; width: 35%;">Incident ID</td>
                <td style="padding: 10px 0; color: #0f172a; font-weight: 600;">${incidentId}</td>
              </tr>
              <tr style="border-bottom: 1px solid #f1f5f9;">
                <td style="padding: 10px 0; color: #64748b;">Business Impact</td>
                <td style="padding: 10px 0; color: #b91c1c; font-weight: 600;">${impact}</td>
              </tr>
            </table>
            <div style="text-align: center; margin-top: 28px;">
              <a href="https://intellidesk-ai-blj5.vercel.app/incidents" style="background-color: #dc2626; color: #ffffff; text-decoration: none; padding: 12px 24px; border-radius: 6px; font-weight: 600; font-size: 14px; display: inline-block;">
                Access Incident Command Workspace
              </a>
            </div>
          </div>
          ${BRAND_FOOTER}
        </div>
      `;
      const text = `ALERT: ${severity} Incident Declared\nID: ${incidentId}\nTitle: ${title}\nImpact: ${impact}`;
      return { subject, html, text };
    }

    default: {
      const subject = `[Notification] Northstar Technologies Service Desk`;
      const html = `
        <div style="max-width: 600px; margin: 0 auto; background-color: #ffffff; border: 1px solid #e2e8f0; border-radius: 8px; overflow: hidden; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;">
          ${BRAND_HEADER}
          <div style="padding: 32px; color: #1e293b;">
            <h2 style="font-size: 18px; font-weight: 600; margin: 0 0 16px 0; color: #0f172a;">IT Service Operations Notification</h2>
            <pre style="background: #f8fafc; padding: 16px; border-radius: 6px; font-size: 12px; overflow-x: auto;">${JSON.stringify(variables, null, 2)}</pre>
          </div>
          ${BRAND_FOOTER}
        </div>
      `;
      const text = `Northstar Technologies Notification: ${JSON.stringify(variables)}`;
      return { subject, html, text };
    }
  }
}
